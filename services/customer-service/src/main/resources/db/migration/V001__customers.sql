-- V001__customers.sql  (customer-service)
--
-- PSP customers, linked to the shared eKYC service.
-- The eKYC owns identity data (names, NIN, documents, photos, address, filiation).
-- This service keeps only what the PSP needs to decide whether a customer may move money.
--
-- customers.id IS the eKYC users.id (same UUID across all services).
-- This service never invents customer IDs: a customer only exists after the eKYC created them.

-- ---------------------------------------------------------------
-- Keep updated_at correct automatically
-- ---------------------------------------------------------------
CREATE FUNCTION public.set_updated_at() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    NEW.updated_at := now();
    RETURN NEW;
END $$;

-- ---------------------------------------------------------------
-- Customers
-- ---------------------------------------------------------------
CREATE TABLE public.customers (
    id                uuid PRIMARY KEY,               -- = ekycsalam.users.id, never generated here
    keycloak_subject  text UNIQUE,                    -- OIDC 'sub' claim, to authenticate API calls
    customer_number   varchar(50) UNIQUE,             -- eKYC customer.customer_number (DAS...)
    phone             varchar(20) UNIQUE
                      CHECK (phone ~ '^\+[1-9][0-9]{7,14}$'),  -- international format, e.g. +213555123456
    display_name      text,                           -- for receipts and "send to" screens only

    -- Synced from the eKYC (same values as the eKYC enums, no translation)
    parcours          text CHECK (parcours IN ('RESIDENT', 'DIASPORA')),
    kyc_status        text NOT NULL DEFAULT 'PENDING'
                      CHECK (kyc_status IN ('PENDING', 'VERIFIED', 'REJECTED', 'BLOCKED')),
    aml_status        text CHECK (aml_status IN ('CLEAR', 'FLAGGED', 'BLOCKED')),
    kyc_verified_at   timestamptz,
    kyc_valid_until   date,                           -- ID document expiry (or residence permit for DIASPORA)
    kyc_synced_at     timestamptz,                    -- last refresh from the eKYC

    -- The customer's relationship with the PSP itself (independent of KYC)
    status            text NOT NULL DEFAULT 'active'
                      CHECK (status IN ('active', 'suspended', 'closed')),

    created_at        timestamptz NOT NULL DEFAULT now(),
    updated_at        timestamptz NOT NULL DEFAULT now()
);

COMMENT ON COLUMN public.customers.id IS
    'Same UUID as ekycsalam.users.id. Never generated by the PSP.';

CREATE TRIGGER customers_set_updated_at
    BEFORE UPDATE ON public.customers
    FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

-- ---------------------------------------------------------------
-- Single source of truth for "may this customer move money?"
-- When this turns false, customer-service freezes the customer's wallet accounts.
-- ---------------------------------------------------------------
CREATE FUNCTION public.customer_can_transact(p_customer_id uuid) RETURNS boolean
LANGUAGE sql STABLE AS $$
    SELECT COALESCE((
        SELECT status = 'active'
           AND kyc_status = 'VERIFIED'
           AND aml_status = 'CLEAR'
           AND (kyc_valid_until IS NULL OR kyc_valid_until >= current_date)
          FROM public.customers
         WHERE id = p_customer_id
    ), false);
$$;

COMMENT ON FUNCTION public.customer_can_transact(uuid) IS
    'True only if the customer is active, KYC VERIFIED, AML CLEAR and the ID document has not expired.';

-- ---------------------------------------------------------------
-- Audit log: who did what, when. Append-only.
-- ---------------------------------------------------------------
CREATE TABLE public.audit_log (
    id           bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    actor_type   text NOT NULL CHECK (actor_type IN ('customer', 'admin', 'system')),
    actor_id     uuid,
    action       text NOT NULL,          -- e.g. 'customer.kyc_synced', 'customer.suspended'
    entity_type  text,
    entity_id    uuid,
    details      jsonb NOT NULL DEFAULT '{}',
    ip_address   inet,
    created_at   timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX audit_entity_idx ON public.audit_log (entity_type, entity_id);
CREATE INDEX audit_actor_idx  ON public.audit_log (actor_id, created_at);

CREATE FUNCTION public.forbid_modification() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION '% is append-only', TG_TABLE_NAME;
END $$;

CREATE TRIGGER audit_no_update_delete
    BEFORE UPDATE OR DELETE ON public.audit_log
    FOR EACH ROW EXECUTE FUNCTION public.forbid_modification();

CREATE TRIGGER audit_no_truncate
    BEFORE TRUNCATE ON public.audit_log
    FOR EACH STATEMENT EXECUTE FUNCTION public.forbid_modification();
